"""Deterministic-mode bit-exact backcompat for ``build_structured_holdout_split``.

Guarantees that after Phase 4's additive changes (new
``learned_oracle_importance`` strategy + ``partition_mode`` config field),
the three original deterministic strategies still produce byte-identical
``support_mask`` / ``target_mask`` outputs at the three canonical support
fractions (0.2, 0.5, 0.8).

The reference is frozen in ``tests/fixtures/holdout_backcompat_reference.npz``,
regenerated by running ``tests/fixtures/generate_holdout_backcompat_reference.py``
on a known-good HEAD.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from dynadiff_vlbi.data.measurement_holdout import build_structured_holdout_split


FIXTURE = Path(__file__).parent / "fixtures" / "holdout_backcompat_reference.npz"
STRATEGIES = ("baseline_track_blocks", "scan_segment_blocks", "station_dropout")
SUPPORT_FRACTIONS = (0.2, 0.5, 0.8)
BASE_SEED = 7
SAMPLE_INDEX = 3


def _toy_observation():
    sequence_length = 3
    image_size = 8
    mask = np.zeros((sequence_length, image_size, image_size), dtype=np.float32)
    frame_uv_indices = np.asarray(
        [
            [[2, 3], [2, 5], [4, 3], [4, 5]],
            [[2, 3], [2, 5], [4, 3], [4, 5]],
            [[2, 3], [2, 5], [4, 3], [4, 5]],
        ],
        dtype=np.int64,
    )
    frame_uv_coords = np.asarray(
        [
            [[-0.7, -0.1], [-0.2, 0.4], [0.2, -0.4], [0.7, 0.1]],
            [[-0.7, -0.1], [-0.2, 0.4], [0.2, -0.4], [0.7, 0.1]],
            [[-0.7, -0.1], [-0.2, 0.4], [0.2, -0.4], [0.7, 0.1]],
        ],
        dtype=np.float32,
    )
    for frame_index in range(sequence_length):
        for row, col in frame_uv_indices[frame_index]:
            mask[frame_index, row, col] = 1.0
    measurements = np.ones((sequence_length, image_size, image_size), dtype=np.complex64)
    baseline_pairs = np.asarray([[0, 1], [1, 2], [0, 2], [0, 3]], dtype=np.int64)
    station_positions = np.asarray(
        [[-0.8, -0.1], [-0.2, 0.7], [0.5, -0.5], [0.8, 0.2]], dtype=np.float32
    )
    return measurements, mask, frame_uv_indices, frame_uv_coords, baseline_pairs, station_positions


def _run_strategy(strategy: str, alpha: float):
    measurements, mask, frame_uv_indices, frame_uv_coords, baseline_pairs, station_positions = (
        _toy_observation()
    )
    kwargs = dict(
        measurements=measurements,
        observed_mask=mask,
        frame_uv_indices=frame_uv_indices,
        frame_uv_coords=frame_uv_coords,
        base_seed=BASE_SEED,
        sample_index=SAMPLE_INDEX,
        support_fraction=alpha,
        strategy=strategy,
    )
    if strategy == "station_dropout":
        kwargs["baseline_pairs"] = baseline_pairs
        kwargs["station_positions"] = station_positions
    return build_structured_holdout_split(**kwargs)


@pytest.fixture(scope="module")
def reference():
    if not FIXTURE.exists():
        pytest.fail(
            f"missing reference fixture at {FIXTURE}; regenerate via "
            "`python tests/fixtures/generate_holdout_backcompat_reference.py`"
        )
    return np.load(FIXTURE)


@pytest.mark.parametrize("strategy", STRATEGIES)
@pytest.mark.parametrize("alpha", SUPPORT_FRACTIONS)
def test_deterministic_strategy_is_bit_exact(reference, strategy: str, alpha: float):
    split = _run_strategy(strategy, alpha)
    tag = f"{strategy}__{alpha:.2f}"
    expected_support = reference[f"{tag}__support_mask"]
    expected_target = reference[f"{tag}__target_mask"]
    expected_support_units = int(reference[f"{tag}__support_unit_count"])
    expected_target_units = int(reference[f"{tag}__target_unit_count"])

    np.testing.assert_array_equal(
        split.support_mask, expected_support,
        err_msg=f"{tag}: support_mask diverged from frozen reference",
    )
    np.testing.assert_array_equal(
        split.target_mask, expected_target,
        err_msg=f"{tag}: target_mask diverged from frozen reference",
    )
    assert split.support_unit_count == expected_support_units, (
        f"{tag}: support_unit_count changed"
    )
    assert split.target_unit_count == expected_target_units, (
        f"{tag}: target_unit_count changed"
    )
    assert split.strategy == strategy


